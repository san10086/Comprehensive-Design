#!/usr/bin/env python3
"""Generate lossless PCM16 HRIR coefficients and the ARM/DSP direction catalog."""
import argparse
from pathlib import Path
import re
import struct
import sys
import wave

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / "assets" / "hrir" / "mit_kemar"
NAME = re.compile(r"([LR])(-?\d+)e(\d{3})a\.wav", re.IGNORECASE)


def read_library(source):
    if not source.is_dir():
        raise ValueError("HRIR source directory does not exist: " + str(source))
    pairs, ignored = {}, []
    for path in sorted(source.rglob("*")):
        if not path.is_file() or path.suffix.lower() != ".wav":
            continue
        match = NAME.fullmatch(path.name)
        if match is None:
            ignored.append(path.relative_to(source).as_posix())
            continue
        ear, elevation, azimuth = match.groups()
        elevation, azimuth = int(elevation), int(azimuth)
        if not (-90 <= elevation <= 90 and 0 <= azimuth <= 359):
            raise ValueError("Invalid angles: " + str(path))
        pair = pairs.setdefault((elevation, azimuth), {})
        ear = ear.upper()
        if ear in pair:
            raise ValueError("Duplicate HRIR direction/ear: " + str(path))
        try:
            with wave.open(str(path), "rb") as wav:
                if (wav.getframerate(), wav.getnchannels(), wav.getsampwidth(),
                        wav.getnframes(), wav.getcomptype()) != (44100, 1, 2, 512, "NONE"):
                    raise ValueError("HRIR must be mono PCM16, 44100 Hz, 512 samples: " + str(path))
                data = wav.readframes(512)
                if len(data) != 1024:
                    raise ValueError("Truncated HRIR: " + str(path))
        except (wave.Error, EOFError) as error:
            raise ValueError("Invalid HRIR WAV: " + str(path)) from error
        pair[ear] = (struct.unpack("<512h", data), path.relative_to(source).as_posix())
    if not pairs:
        raise ValueError("No HRIR pairs found in " + str(source))
    for angles, pair in pairs.items():
        if set(pair) != {"L", "R"}:
            raise ValueError("Missing left/right pair for " + str(angles))
    # These directions are required by the existing compatibility commands.
    for angles in ((40, 45), (60, 250)):
        if angles not in pairs:
            raise ValueError("Missing compatibility direction: " + str(angles))
    return dict(sorted(pairs.items())), ignored


def render(pairs):
    banner = "/* Generated by tools/generate_hrir.py; do not edit. */\n"
    header = [banner, "#ifndef HRIR_CATALOG_H\n#define HRIR_CATALOG_H\n",
              "#define HRIR_DIRECTION_CODE(e, a) (360 * ((e) + 90) + (a))\n",
              "#define HRIR_DIRECTION_COUNT %d\n" % len(pairs),
              "typedef struct { int elevation; int azimuth; int code; } HrirDirection;\n",
              "static const HrirDirection kHrirDirections[HRIR_DIRECTION_COUNT] = {\n"]
    coefficients = [banner,
                    "static const int16_t kHrirCoefficients[HRIR_DIRECTION_COUNT][2][DSP_SPATIAL_HRIR_LENGTH] = {\n"]
    for (elevation, azimuth), pair in pairs.items():
        code = 360 * (elevation + 90) + azimuth
        header.append("    {%d, %d, %d},\n" % (elevation, azimuth, code))
        coefficients.append("    { /* elevation %d, azimuth %d */\n" % (elevation, azimuth))
        for ear in ("L", "R"):
            samples, filename = pair[ear]
            coefficients.append("        { /* %s */\n" % filename)
            for offset in range(0, 512, 12):
                coefficients.append("            " + ", ".join(map(str, samples[offset:offset + 12])) + ",\n")
            coefficients.append("        },\n")
        coefficients.append("    },\n")
    header.append("};\nstatic inline int hrir_direction_index(int code)\n{\n"
                  "    int low = 0, high = HRIR_DIRECTION_COUNT - 1;\n"
                  "    while (low <= high) {\n"
                  "        int mid = low + (high - low) / 2;\n"
                  "        if (kHrirDirections[mid].code == code) return mid;\n"
                  "        if (kHrirDirections[mid].code < code) low = mid + 1;\n"
                  "        else high = mid - 1;\n"
                  "    }\n    return -1;\n}\n#endif\n")
    coefficients.append("};\n")
    return {"shared/hrir_catalog.h": "".join(header),
            "dsp/dsp_spatial_coefficients.inc": "".join(coefficients)}


def generate(source, root, check=False):
    pairs, ignored = read_library(source)
    outputs = render(pairs)  # Validate the entire library before any writes.
    for name, content in outputs.items():
        path = root / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise ValueError("Generated file is stale: " + name + "; run make hrir")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode("utf-8"))
    print("HRIR %s: %d directions, %d WAVs, %d coefficient bytes" %
          ("check PASS" if check else "generated", len(pairs), 2 * len(pairs), 2048 * len(pairs)))
    for filename in ignored:
        print("  ignored non-direction WAV: " + filename)
    return pairs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        generate(args.source, ROOT, args.check)
    except (OSError, ValueError) as error:
        print("HRIR error: " + str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
